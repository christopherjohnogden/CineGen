import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL, fileURLToPath } from 'node:url';

const source = new URL('../mcp/media-viewer-client.mjs', import.meta.url);
const output = new URL('../mcp/media-viewer-script.mjs', import.meta.url);

export async function compileMcpViewer() {
  const result = await build({
    entryPoints: [fileURLToPath(source)], bundle: true, write: false,
    platform: 'browser', format: 'iife', target: 'safari16', minify: true,
  });
  // Ship a complete browser program as data. Serializing a server function
  // loses helpers injected by Wrangler's keepNames transform (e.g. __name).
  const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  return `// Generated by scripts/build-mcp-viewer.mjs. Edit media-viewer-client.mjs instead.\nexport const MEDIA_VIEWER_SCRIPT = ${JSON.stringify(script)};\n`;
}

export async function buildMcpViewer() {
  const compiled = await compileMcpViewer();
  if (await readFile(output, 'utf8').catch(() => '') !== compiled) await writeFile(output, compiled);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await buildMcpViewer();
